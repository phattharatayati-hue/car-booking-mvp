import { NextResponse } from "next/server";

/* เลิกให้ลูกค้าเซ็นรับใบเสร็จบนหน้าจอแล้ว
   ใบเสร็จลงนามจากระบบโดยผู้มีอำนาจของบริษัททั้งสองช่อง
   คงปลายทางนี้ไว้เพื่อตอบให้ชัดเจน เผื่อมีหน้าเก่าค้างอยู่ในมือถือของคนส่งรถ */
export async function POST() {
  return NextResponse.json(
    { error: "ยกเลิกการให้ลูกค้าเซ็นรับใบเสร็จแล้ว — ใบเสร็จลงนามจากระบบให้อัตโนมัติ" },
    { status: 410 }
  );
}
